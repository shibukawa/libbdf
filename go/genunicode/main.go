// gen-unicode writes src/unicode_nfc.h: the tables of canonical
// normalisation (NFC), taken from golang.org/x/text/unicode/norm, the
// package the reference implementation normalises passwords with, so that
// both read the same version of the Unicode data.
//
//	cd go && go run ./genunicode ../src/unicode_nfc.h
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

const (
	hangulBase = 0xAC00
	hangulEnd  = 0xD7A3
)

func main() {
	type decomp struct {
		cp  rune
		seq []rune
	}
	type pair struct{ a, b, c rune }
	type cccRange struct {
		lo, hi rune
		ccc    uint8
	}
	var decomps []decomp
	var pairs []pair
	var cccs []cccRange
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		s := string(r)
		p := norm.NFD.PropertiesString(s)
		if c := p.CCC(); c != 0 {
			if n := len(cccs); n > 0 && cccs[n-1].hi == r-1 && cccs[n-1].ccc == c {
				cccs[n-1].hi = r
			} else {
				cccs = append(cccs, cccRange{r, r, c})
			}
		}
		if r >= hangulBase && r <= hangulEnd {
			continue // by arithmetic
		}
		d := []rune(norm.NFD.String(s))
		if len(d) == 1 && d[0] == r {
			continue
		}
		decomps = append(decomps, decomp{r, d})
		// a primary composite: stable under NFC, and made of what its
		// decomposition without the last character composes to, and that
		// last character
		if len(d) >= 2 && norm.NFC.String(s) == s {
			head := []rune(norm.NFC.String(string(d[:len(d)-1])))
			last := d[len(d)-1]
			if len(head) == 1 && norm.NFC.String(string([]rune{head[0], last})) == s {
				pairs = append(pairs, pair{head[0], last, r})
			}
		}
	}
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].a != pairs[j].a {
			return pairs[i].a < pairs[j].a
		}
		return pairs[i].b < pairs[j].b
	})

	var w strings.Builder
	fmt.Fprintf(&w, "/* Generated by go/genunicode from golang.org/x/text/unicode/norm (Unicode %s);\n * do not edit. The tables of canonical normalisation: decompositions (full,\n * without Hangul syllables, which are computed), combining classes and the\n * pairs that compose. */\n\n", norm.Version)
	fmt.Fprintf(&w, "#define BDFI_UNICODE_VERSION \"%s\"\n\n", norm.Version)

	// decompositions: code point, offset into the pool, length
	var pool []rune
	fmt.Fprintf(&w, "/* {code point, offset in bdfi_nfd_pool, length}, by code point */\nstatic const uint32_t bdfi_nfd_index[%d][3] = {\n", len(decomps))
	for i, d := range decomps {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, %d, %d},", d.cp, len(pool), len(d.seq))
		pool = append(pool, d.seq...)
		if i%4 == 3 || i == len(decomps)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")
	fmt.Fprintf(&w, "static const uint32_t bdfi_nfd_pool[%d] = {\n", len(pool))
	for i, r := range pool {
		if i%10 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " 0x%X,", r)
		if i%10 == 9 || i == len(pool)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")

	fmt.Fprintf(&w, "/* {first, last, canonical combining class}, by code point */\nstatic const uint32_t bdfi_ccc_ranges[%d][3] = {\n", len(cccs))
	for i, c := range cccs {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X, %d},", c.lo, c.hi, c.ccc)
		if i%4 == 3 || i == len(cccs)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")

	fmt.Fprintf(&w, "/* {first, second, composite}, by first and then second */\nstatic const uint32_t bdfi_nfc_pairs[%d][3] = {\n", len(pairs))
	for i, p := range pairs {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X, 0x%X},", p.a, p.b, p.c)
		if i%4 == 3 || i == len(pairs)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n")
	if err := os.WriteFile(os.Args[1], []byte(w.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "Unicode %s: %d decompositions (%d code points), %d combining class ranges, %d pairs\n", norm.Version, len(decomps), len(pool), len(cccs), len(pairs))
}
