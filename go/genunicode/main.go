// gen-unicode writes src/unicode_nfc.h: the tables of canonical
// normalisation (NFC), taken from golang.org/x/text/unicode/norm, the
// package the reference implementation normalises passwords with, so that
// both read the same version of the Unicode data.
//
//	cd go && go run ./genunicode ../src/unicode_nfc.h
//
// With a second file name it also writes the tables that drawing text
// needs (see textTables):
//
//	cd go && go run ./genunicode ../src/unicode_nfc.h ../src/unicode_text.h
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/bidi"
	"golang.org/x/text/unicode/norm"
)

const (
	hangulBase = 0xAC00
	hangulEnd  = 0xD7A3
)

func main() {
	type decomp struct {
		cp  rune
		seq []rune
	}
	type pair struct{ a, b, c rune }
	type cccRange struct {
		lo, hi rune
		ccc    uint8
	}
	var decomps []decomp
	var pairs []pair
	var cccs []cccRange
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		s := string(r)
		p := norm.NFD.PropertiesString(s)
		if c := p.CCC(); c != 0 {
			if n := len(cccs); n > 0 && cccs[n-1].hi == r-1 && cccs[n-1].ccc == c {
				cccs[n-1].hi = r
			} else {
				cccs = append(cccs, cccRange{r, r, c})
			}
		}
		if r >= hangulBase && r <= hangulEnd {
			continue // by arithmetic
		}
		d := []rune(norm.NFD.String(s))
		if len(d) == 1 && d[0] == r {
			continue
		}
		decomps = append(decomps, decomp{r, d})
		// a primary composite: stable under NFC, and made of what its
		// decomposition without the last character composes to, and that
		// last character
		if len(d) >= 2 && norm.NFC.String(s) == s {
			head := []rune(norm.NFC.String(string(d[:len(d)-1])))
			last := d[len(d)-1]
			if len(head) == 1 && norm.NFC.String(string([]rune{head[0], last})) == s {
				pairs = append(pairs, pair{head[0], last, r})
			}
		}
	}
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].a != pairs[j].a {
			return pairs[i].a < pairs[j].a
		}
		return pairs[i].b < pairs[j].b
	})

	var w strings.Builder
	fmt.Fprintf(&w, "/* Generated by go/genunicode from golang.org/x/text/unicode/norm (Unicode %s);\n * do not edit. The tables of canonical normalisation: decompositions (full,\n * without Hangul syllables, which are computed), combining classes and the\n * pairs that compose. */\n\n", norm.Version)
	fmt.Fprintf(&w, "#define BDFI_UNICODE_VERSION \"%s\"\n\n", norm.Version)

	// decompositions: code point, offset into the pool, length
	var pool []rune
	fmt.Fprintf(&w, "/* {code point, offset in bdfi_nfd_pool, length}, by code point */\nstatic const uint32_t bdfi_nfd_index[%d][3] = {\n", len(decomps))
	for i, d := range decomps {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, %d, %d},", d.cp, len(pool), len(d.seq))
		pool = append(pool, d.seq...)
		if i%4 == 3 || i == len(decomps)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")
	fmt.Fprintf(&w, "static const uint32_t bdfi_nfd_pool[%d] = {\n", len(pool))
	for i, r := range pool {
		if i%10 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " 0x%X,", r)
		if i%10 == 9 || i == len(pool)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")

	fmt.Fprintf(&w, "/* {first, last, canonical combining class}, by code point */\nstatic const uint32_t bdfi_ccc_ranges[%d][3] = {\n", len(cccs))
	for i, c := range cccs {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X, %d},", c.lo, c.hi, c.ccc)
		if i%4 == 3 || i == len(cccs)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")

	fmt.Fprintf(&w, "/* {first, second, composite}, by first and then second */\nstatic const uint32_t bdfi_nfc_pairs[%d][3] = {\n", len(pairs))
	for i, p := range pairs {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X, 0x%X},", p.a, p.b, p.c)
		if i%4 == 3 || i == len(pairs)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n")
	if err := os.WriteFile(os.Args[1], []byte(w.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "Unicode %s: %d decompositions (%d code points), %d combining class ranges, %d pairs\n", norm.Version, len(decomps), len(pool), len(cccs), len(pairs))
	if len(os.Args) > 2 {
		textTables(os.Args[2])
	}
}

// textTables writes src/unicode_text.h: what drawing text takes of the
// Unicode data beyond form C. The names of font families are compared in
// form KC and in lower case (the compatibility decompositions and Go's
// unicode.ToLower), runs of right-to-left characters are found by their
// bidirectional class (golang.org/x/text/unicode/bidi), and a search keeps
// combining marks (Go's unicode.M) with the character before them.
func textTables(path string) {
	type decomp struct {
		cp  rune
		seq []rune
	}
	var decomps []decomp
	var lower [][2]rune
	type bidiRange struct {
		lo, hi rune
		rtl    int
	}
	var bidis []bidiRange
	var marks [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if unicode.Is(unicode.M, r) {
			if n := len(marks); n > 0 && marks[n-1][1] == r-1 {
				marks[n-1][1] = r
			} else {
				marks = append(marks, [2]rune{r, r})
			}
		}
		s := string(r)
		if kd := norm.NFKD.String(s); kd != norm.NFD.String(s) {
			decomps = append(decomps, decomp{r, []rune(kd)})
		}
		if l := unicode.ToLower(r); l != r {
			lower = append(lower, [2]rune{r, l})
		}
		p, _ := bidi.LookupRune(r)
		rtl := -1 // neutral: takes the direction around it
		switch p.Class() {
		case bidi.R, bidi.AL:
			rtl = 1
		case bidi.L, bidi.EN, bidi.AN:
			rtl = 0
		}
		if rtl >= 0 {
			if n := len(bidis); n > 0 && bidis[n-1].hi == r-1 && bidis[n-1].rtl == rtl {
				bidis[n-1].hi = r
			} else {
				bidis = append(bidis, bidiRange{r, r, rtl})
			}
		}
	}
	var w strings.Builder
	fmt.Fprintf(&w, "/* Generated by go/genunicode from golang.org/x/text/unicode/norm and\n * unicode/bidi (Unicode %s) and from Go's unicode package (Unicode %s);\n * do not edit. What drawing text takes of the Unicode data: the\n * compatibility decompositions, lower case, and the direction of\n * characters. */\n\n", norm.Version, unicode.Version)
	var pool []rune
	fmt.Fprintf(&w, "/* The characters whose decomposition in form KD is not the canonical one:\n * {code point, offset in bdfi_nfkd_pool, length}, by code point */\nstatic const uint32_t bdfi_nfkd_index[%d][3] = {\n", len(decomps))
	for i, d := range decomps {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, %d, %d},", d.cp, len(pool), len(d.seq))
		pool = append(pool, d.seq...)
		if i%4 == 3 || i == len(decomps)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")
	fmt.Fprintf(&w, "static const uint32_t bdfi_nfkd_pool[%d] = {\n", len(pool))
	for i, r := range pool {
		if i%10 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " 0x%X,", r)
		if i%10 == 9 || i == len(pool)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")
	fmt.Fprintf(&w, "/* {character, its lower case} where they differ, by character */\nstatic const uint32_t bdfi_lower_pairs[%d][2] = {\n", len(lower))
	for i, l := range lower {
		if i%5 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X},", l[0], l[1])
		if i%5 == 4 || i == len(lower)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")
	fmt.Fprintf(&w, "/* {first, last, direction} of the characters that have one of their own:\n * 1 for right to left (classes R and AL), 0 for left to right (L, EN and\n * AN). The others take the direction around them. By code point. */\nstatic const uint32_t bdfi_bidi_ranges[%d][3] = {\n", len(bidis))
	for i, b := range bidis {
		if i%4 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X, %d},", b.lo, b.hi, b.rtl)
		if i%4 == 3 || i == len(bidis)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n\n")
	fmt.Fprintf(&w, "/* {first, last} of the combining marks (the general categories Mn, Mc and\n * Me: \\p{M} of a regular expression), which a search keeps with the\n * character before them */\nstatic const uint32_t bdfi_mark_ranges[%d][2] = {\n", len(marks))
	for i, m := range marks {
		if i%5 == 0 {
			w.WriteString("   ")
		}
		fmt.Fprintf(&w, " {0x%X, 0x%X},", m[0], m[1])
		if i%5 == 4 || i == len(marks)-1 {
			w.WriteString("\n")
		}
	}
	w.WriteString("};\n")
	if err := os.WriteFile(path, []byte(w.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "text: %d compatibility decompositions (%d code points), %d lower case pairs, %d ranges of direction, %d ranges of marks\n", len(decomps), len(pool), len(lower), len(bidis), len(marks))
}
