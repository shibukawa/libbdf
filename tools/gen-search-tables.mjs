// Writes src/unicode_fold.h: what the reference's TypeScript reader makes of
// each character when it normalises text for a search (normalizeChar of
// packages/core/src/search.ts: NFKC, lower case, katakana as hiragana, the
// minus sign as a hyphen). The tables are that function, asked about every
// code point, so libbdf finds what the reference's viewer finds.
//
//   node tools/gen-search-tables.mjs <bdf checkout> src/unicode_fold.h
//
// The checkout must have packages/core built. The Unicode version is that of
// the node that runs this (process.versions.unicode).
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const [root, out] = process.argv.slice(2);
if (!root || !out) {
  console.error("usage: gen-search-tables.mjs <bdf checkout> <out.h>");
  process.exit(2);
}
const { normalizeChar } = await import(pathToFileURL(join(root, "packages/core/dist/index.js")).href);
const points = (s) => [...s].map((c) => c.codePointAt(0));

// fold: a character as a case-sensitive search has it, where it is not
// itself. lower: as a search that ignores case has it, where that differs.
const fold = [], lower = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const ch = String.fromCodePoint(cp);
  const sensitive = normalizeChar(ch, true), insensitive = normalizeChar(ch, false);
  if (cp < 0x80) {
    // the library does ASCII without the tables
    const want = cp >= 0x41 && cp <= 0x5a ? String.fromCodePoint(cp + 32) : ch;
    if (sensitive !== ch || insensitive !== want) throw new Error(`ASCII ${cp} is not what the library assumes`);
    continue;
  }
  if (sensitive !== ch) fold.push([cp, points(sensitive)]);
  if (insensitive !== sensitive) lower.push([cp, points(insensitive)]);
}

// A table as ranges of characters that map to one character each, a fixed
// step apart and a fixed distance away, and the rest with their strings.
function table(name, entries) {
  const single = entries.filter(([, to]) => to.length === 1).map(([cp, to]) => [cp, to[0]]);
  const multi = entries.filter(([, to]) => to.length !== 1);
  const ranges = [];
  for (let i = 0; i < single.length;) {
    const [cp, to] = single[i];
    let j = i + 1, step = 1;
    if (j < single.length && single[j][1] - single[j][0] === to - cp && single[j][0] - cp <= 2) {
      step = single[j][0] - cp;
      while (j < single.length && single[j][0] - single[j - 1][0] === step && single[j][1] - single[j][0] === to - cp) j++;
    }
    ranges.push([cp, single[j - 1][0], to, step]);
    i = j;
  }
  const pool = [];
  const strings = multi.map(([cp, to]) => {
    if (to.length > 255) throw new Error("a mapping longer than the table can say");
    const at = pool.length;
    pool.push(...to);
    return [cp, at, to.length];
  });
  const hex = (v) => "0x" + v.toString(16).toUpperCase();
  const rows = (list, each, perLine) => {
    const lines = [];
    for (let i = 0; i < list.length; i += perLine) lines.push("    " + list.slice(i, i + perLine).map(each).join(" "));
    return lines.join("\n");
  };
  return `/* ${name}: ${single.length} characters that become one other in ${ranges.length} ranges
 * (the first, the last with the step between them in its top byte, what the
 * first becomes), and ${multi.length} that become several or none (the character,
 * where its string starts in the pool, how long it is). */
static const uint32_t bdfi_${name}_ranges[${ranges.length}][3] = {
${rows(ranges, ([a, b, to, step]) => `{${hex(a)}, ${hex(b + step * 0x1000000)}, ${hex(to)}},`, 3)}
};
static const uint32_t bdfi_${name}_strings[${Math.max(strings.length, 1)}][3] = {
${strings.length ? rows(strings, ([cp, at, n]) => `{${hex(cp)}, ${at}, ${n}},`, 5) : "    {0, 0, 0},"}
};
#define BDFI_${name.toUpperCase()}_STRINGS ${strings.length}
static const uint32_t bdfi_${name}_pool[${Math.max(pool.length, 1)}] = {
${pool.length ? rows(pool, (v) => hex(v) + ",", 10) : "    0,"}
};
`;
}

const text = `/* Generated by tools/gen-search-tables.mjs from the reference's
 * normalizeChar (packages/core/src/search.ts) under Unicode ${process.versions.unicode}:
 * what a character is to a search. Do not edit. */
#ifndef BDF_UNICODE_FOLD_H
#define BDF_UNICODE_FOLD_H

#define BDFI_FOLD_UNICODE_VERSION "${process.versions.unicode}"

${table("fold", fold)}
${table("lower", lower)}
#endif /* BDF_UNICODE_FOLD_H */
`;
await writeFile(out, text);
console.error(`${fold.length} folded, ${lower.length} lowered, ${text.length} bytes`);
