#!/usr/bin/env python3
"""Joins libbdf's sources into one header, bdf.h.

Included as it is, the result declares the public API. The one translation
unit that defines BDF_IMPLEMENTATION before including it gets the whole
library as well, with the internals static (BDF_INTERNAL). Define BDF_STATIC
too to keep the API out of the link namespace. The implementation is C11;
a C++ translation unit should include the header without BDF_IMPLEMENTATION
and compile the implementation in a .c file of its own.

The split sources stay the form the library is developed and tested in;
this script runs at build time (the bdf_single_header target) and at
release time.
"""

import argparse
import pathlib
import re

ORDER = [
    "reader.c",
    "object.c",
    "container.c",
    "inflate.c",
    "json.c",
    "manifest.c",
    "doc.c",
    "version.c",
]

LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"(bdf/bdf\.h|bdf_internal\.h)"\s*$')


def strip_local_includes(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not LOCAL_INCLUDE.match(line)) + "\n"


def main() -> None:
    root = pathlib.Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", type=pathlib.Path, default=root / "dist" / "bdf.h")
    args = ap.parse_args()

    public = (root / "include" / "bdf" / "bdf.h").read_text(encoding="utf-8")
    internal = (root / "src" / "bdf_internal.h").read_text(encoding="utf-8")
    version = re.search(r'#define BDF_VERSION_STRING\s+"([^"]+)"', public).group(1)

    out = []
    out.append(f"/*\n * bdf.h — the single-header build of libbdf {version}.\n"
               " * Generated by tools/amalgamate.py from include/bdf/bdf.h and src/; do not edit.\n"
               " * See the preamble of the public header below for how to use it.\n */\n")
    out.append(public)
    out.append("\n#ifdef BDF_IMPLEMENTATION\n")
    out.append("#ifndef BDF_INTERNAL\n#define BDF_INTERNAL static\n#endif\n")
    out.append("\n/* ==== src/bdf_internal.h ================================================= */\n\n")
    out.append(strip_local_includes(internal))
    for name in ORDER:
        text = (root / "src" / name).read_text(encoding="utf-8")
        out.append(f"\n/* ==== src/{name} {'=' * max(1, 70 - len(name))} */\n\n")
        out.append(strip_local_includes(text))
    out.append("\n#endif /* BDF_IMPLEMENTATION */\n")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
